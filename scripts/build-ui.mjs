import { readFileSync, writeFileSync } from 'node:fs';
const html = readFileSync(new URL('../ui/index.html', import.meta.url), 'utf8');
writeFileSync(new URL('../src/ui.ts', import.meta.url), `// GENERATED by scripts/build-ui.mjs from ui/index.html — do not edit by hand.\nexport const HTML = ${JSON.stringify(html)};\n`);
console.log('ui.ts written', html.length, 'bytes');
